-- Logged activities (showers this term) and their details. See docs/erd.md.

CREATE TABLE activity_types (
    id   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL UNIQUE
);

INSERT INTO activity_types (name) VALUES ('SHOWER');

CREATE TABLE activity_logs (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type_id    BIGINT      NOT NULL REFERENCES activity_types (id) ON DELETE RESTRICT,
    logged_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    local_date DATE        NOT NULL,
    minutes    INTEGER     NOT NULL
);

-- Streaks, scores and the leaderboard all read one user's logs by day.
CREATE INDEX activity_logs_user_id_local_date_idx ON activity_logs (user_id, local_date);

CREATE TABLE shower_details (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id      BIGINT  NOT NULL UNIQUE REFERENCES activity_logs (id) ON DELETE CASCADE,
    shampoo     BOOLEAN NOT NULL DEFAULT FALSE,
    conditioner BOOLEAN NOT NULL DEFAULT FALSE,
    body_wash   BOOLEAN NOT NULL DEFAULT FALSE,
    exfoliant   BOOLEAN NOT NULL DEFAULT FALSE
);
